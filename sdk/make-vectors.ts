import { generateKeyPairSync, randomBytes, createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { Signer, PqSigner } from '../api/src/receipt';
import { toMoon, formatMoonmark, toUnixNs, parseMoonmark } from '../api/src/moon';
const pq = new PqSigner(new Uint8Array(randomBytes(32)));
const ed = new Signer(generateKeyPairSync('ed25519').privateKey, pq);
const edV1 = new Signer(generateKeyPairSync('ed25519').privateKey);   // no PQ: v1/v2 receipts
const keys: Record<string, string> = { [ed.keyId]: ed.info().public_key, [pq.keyId]: pq.info().public_key, [edV1.keyId]: edV1.info().public_key };
const beacon = { network: 'drand-quicknet' as const, round: 34027716, signature: '85da5815af1a8b1f7abbbe3237520b18658213dc0a8349ef983dd45d22b1a0868e5d442ed7273e3220bf168b83000b1c' };
const text = 'Moon SDK conformance vector: hello, moon';
const sha = createHash('sha256').update(text).digest('hex');
const ns = 1794886514418000000n;   // the moment Moon signed this text in production; after the beacon round
const mk = formatMoonmark(toMoon(ns));
const v3 = ed.sign(sha, mk, ns, beacon);
const v2 = edV1.sign(sha, mk, ns, beacon);
const v1 = edV1.sign(sha, mk, ns, null);
const clone = (x: unknown) => JSON.parse(JSON.stringify(x));
const bad = (name: string, r: any, reason: string, mutate: (r: any) => void) => { const c = clone(r); mutate(c); return { name, receipt: c, reason }; };
const conversions = [0n, 1n, -1n, 1700000000000000000n, 1794886514418000000n, 947182440000000000n, -62165308562978611200n, 4102444800123456789n].map((u) => {
  const m = formatMoonmark(toMoon(u)); return { unix_ns: u.toString(), moonmark: m, earliest_unix_ns: toUnixNs(parseMoonmark(m)).toString() };
});
const out = {
  about: 'Moon SDK conformance vectors. Every SDK must reproduce all of these. Generated by sdk/make-vectors (see README).',
  text, sha256: sha, keys,
  beacon_chain: { network: 'drand-quicknet', public_key: '83cf0f2896adee7eb8b5f01fcad3912212c437e0073e911fb90022d3e760183c8c4b450b6a0a6c3ac6a5776a2d1064510d1fec758c921cc22b0e17e63aaf4bcb5ed66304de9cf809bd274ca73bab4af5a6e9c76a4bc09e76eae8991ef5ece45a', period: 3, genesis_time: 1692803367, dst: 'BLS_SIG_BLS12381G1_XMD:SHA-256_SSWU_RO_NUL_' },
  conversions,
  valid: [{ name: 'v3 hybrid with beacon', receipt: v3, not_before_round: 34027716, post_quantum: true }, { name: 'v2 with beacon', receipt: v2, not_before_round: 34027716 }, { name: 'v1', receipt: v1 }],
  invalid: [
    bad('tampered sha256', v3, 'bad_signature', (r) => { r.sha256 = 'f' + r.sha256.slice(1); }),
    bad('tampered ed25519 signature', v1, 'bad_signature', (r) => { r.signature = (r.signature[0] === 'A' ? 'B' : 'A') + r.signature.slice(1); }),
    bad('tampered pq signature', v3, 'bad_pq_signature', (r) => { const s0 = r.pq.signature; r.pq.signature = s0.slice(0, 5) + (s0[5] === 'A' ? 'B' : 'A') + s0.slice(6); }),
    { name: 'forged beacon', receipt: edV1.sign(sha, mk, ns, { ...beacon, signature: 'a' + beacon.signature.slice(1) }), reason: 'bad_beacon' },
    { name: 'signed before its beacon existed', receipt: edV1.sign(sha, formatMoonmark(toMoon(1794886000000000000n)), 1794886000000000000n, beacon), reason: 'beacon_after_moment' },
    { name: 'moonmark does not match unix_ns', receipt: edV1.sign(sha, formatMoonmark(toMoon(ns + 1000000000n)), ns, null), reason: 'moonmark_mismatch' },
    bad('unknown key', v1, 'unknown_key', (r) => { r.key_id = '0000000000000000'; }),
    bad('unknown version', v1, 'unknown_version', (r) => { r.receipt = 'moonmark-receipt/9'; }),
  ],
  content: { matches: sha, other: createHash('sha256').update(text + '!').digest('hex'), reason: 'content_mismatch' },
};
writeFileSync(new URL('./vectors.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
console.log('ok', Object.keys(keys).length, mk);
