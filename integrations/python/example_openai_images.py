"""Sign every image an image API returns, the moment you save it. Shown with the OpenAI Python SDK; the same two
lines work after any generator (Flux, Stability, Replicate, your own model): save the bytes, then sign_file().

    pip install openai
    python example_openai_images.py "a lighthouse at dusk"
"""
import base64, sys
from openai import OpenAI          # any image API works the same way
from moon_sign import sign_file

MODEL = "gpt-image-1"
prompt = sys.argv[1] if len(sys.argv) > 1 else "a lighthouse at dusk"
img = OpenAI().images.generate(model=MODEL, prompt=prompt)
path = "generated.png"
with open(path, "wb") as f:
    f.write(base64.b64decode(img.data[0].b64_json))

res = sign_file(path, label="AI-generated by %s" % MODEL)    # writes generated.png.moonmark.json
print("Signed at", res["receipt"]["moonmark"][:19], "->", res["signed_url"])
