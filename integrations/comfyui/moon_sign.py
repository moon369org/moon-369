"""Sign files and generated output on Moon. Standard library only (Python 3.8+).

Only SHA-256 fingerprints (and, if you pass one, a look-alike hash) leave your machine.

    from moon_sign import sign_file, sign_bytes
    sign_file("out.png", label="AI-generated by flux-dev")     # writes out.png.moonmark.json, returns the response
    sign_bytes(b"any bytes")                                    # just signs; returns the response

Set MOON_KEY (free at https://moon369.org/api#key) to register under your verified name and lift the rate limit.
"""
import hashlib, json, os, urllib.request, urllib.error

API = os.environ.get("MOON_API", "https://api.moon369.org").rstrip("/")


class MoonError(Exception):
    pass


def sha256_file(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def sign_sha256(sha256, label=None, key=None, timeout=15):
    """Have Moon sign a fingerprint. Returns Moon's response: receipt, signed_url, moonmark_url, utc."""
    body = {"sha256": sha256}
    if label:
        body["label"] = str(label)[:120]
    headers = {"Content-Type": "application/json", "User-Agent": "moon-sign-py/1"}
    key = key or os.environ.get("MOON_KEY")
    if key:
        headers["Authorization"] = "Bearer " + key
    req = urllib.request.Request(API + "/v1/sign", data=json.dumps(body).encode(), headers=headers, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        try:
            msg = json.load(e).get("error", {}).get("message")
        except Exception:
            msg = None
        raise MoonError(msg or "Moon returned %s" % e.code) from None
    except urllib.error.URLError as e:
        raise MoonError("Could not reach Moon: %s" % e.reason) from None


def sign_bytes(data, label=None, key=None):
    return sign_sha256(hashlib.sha256(data).hexdigest(), label, key)


def sign_file(path, label=None, key=None, sidecar=True):
    """Sign a file's exact bytes. Writes <path>.moonmark.json (the receipt) unless sidecar=False."""
    res = sign_sha256(sha256_file(path), label or os.path.basename(path), key)
    if sidecar:
        with open(path + ".moonmark.json", "w", encoding="utf-8") as f:
            json.dump(res["receipt"], f, indent=2)
            f.write("\n")
    return res


if __name__ == "__main__":
    import sys
    if len(sys.argv) < 2:
        sys.exit("Usage: python moon_sign.py <files...>")
    for p in sys.argv[1:]:
        r = sign_file(p)
        print("%s  %s  %s" % (p, r["receipt"]["moonmark"][:19], r["signed_url"]))
