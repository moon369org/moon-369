"""Moon for ComfyUI: a Save Image node that signs every image on Moon the moment it's saved.

Each PNG gets <name>.png.moonmark.json next to it, holding Moon's signed receipt (Ed25519 + ML-DSA-65, with a
public drand beacon). Only the file's SHA-256 leaves your machine. Set MOON_KEY to register under your name.
"""
import os
import folder_paths
from nodes import SaveImage
from .moon_sign import sign_file, MoonError


class MoonSaveImage(SaveImage):
    CATEGORY = "image"
    DESCRIPTION = "Saves images and signs each one on Moon, with a proof link anyone can check."

    @classmethod
    def INPUT_TYPES(cls):
        t = super().INPUT_TYPES()
        t["required"]["filename_prefix"] = ("STRING", {"default": "Moon"})
        t["required"]["generator"] = ("STRING", {"default": "ComfyUI", "tooltip": "Recorded in the label: AI-generated by <generator>"})
        return t

    def save_images(self, images, filename_prefix="Moon", generator="ComfyUI", prompt=None, extra_pnginfo=None):
        out = super().save_images(images, filename_prefix, prompt, extra_pnginfo)
        base = folder_paths.get_output_directory()
        for img in out.get("ui", {}).get("images", []):
            path = os.path.join(base, img.get("subfolder", ""), img["filename"])
            try:
                r = sign_file(path, label="AI-generated by %s: %s" % (generator or "ComfyUI", img["filename"]))
                print("[Moon] signed %s at %s  %s" % (img["filename"], r["receipt"]["moonmark"][:19], r["signed_url"]))
            except (MoonError, OSError) as e:
                print("[Moon] %s was saved but not signed: %s" % (img["filename"], e))
        return out


NODE_CLASS_MAPPINGS = {"MoonSaveImage": MoonSaveImage}
NODE_DISPLAY_NAME_MAPPINGS = {"MoonSaveImage": "Save Image (signed on Moon)"}
