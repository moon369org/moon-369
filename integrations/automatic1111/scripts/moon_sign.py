"""Moon for Automatic1111 / Forge: sign every image the moment the web UI saves it.

Writes <image>.moonmark.json next to each image and prints the proof link. Only the file's SHA-256 leaves your
machine. Set MOON_KEY to register under your verified name. Turn it off with MOON_SIGN=0.
"""
import os
from modules import script_callbacks
try:
    from moon_sign_lib import sign_file, MoonError
except ImportError:  # the web UI loads scripts by path
    import importlib.util
    _spec = importlib.util.spec_from_file_location("moon_sign_lib", os.path.join(os.path.dirname(__file__), "moon_sign_lib.py"))
    _mod = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(_mod)
    sign_file, MoonError = _mod.sign_file, _mod.MoonError


def on_image_saved(params):
    if os.environ.get("MOON_SIGN", "1") == "0":
        return
    path = getattr(params, "filename", None)
    if not path or not os.path.isfile(path):
        return
    model = getattr(getattr(params, "p", None), "sd_model_name", None) or "Stable Diffusion"
    try:
        r = sign_file(path, label="AI-generated by %s: %s" % (model, os.path.basename(path)))
        print("[Moon] signed %s at %s  %s" % (os.path.basename(path), r["receipt"]["moonmark"][:19], r["signed_url"]))
    except (MoonError, OSError) as e:
        print("[Moon] %s was saved but not signed: %s" % (os.path.basename(path), e))


script_callbacks.on_image_saved(on_image_saved)
